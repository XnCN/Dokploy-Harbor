import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {fileURLToPath, pathToFileURL} from 'node:url';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {buildCompose,yaml} from './render-compose.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
export async function check() {
  const lock=JSON.parse(await readFile(path.join(root,'images.lock.json'),'utf8'));
  assert.equal(lock.platform,'linux/amd64');
  assert.match(lock.harbor_version,/^v\d+\.\d+\.\d+$/);
  for (const item of Object.values(lock.images)) {
    assert.match(item.digest,/^sha256:[a-f0-9]{64}$/);
    assert.ok(item.tag!=='latest');
    assert.ok(Array.isArray(item.entrypoint)&&Array.isArray(item.command));
  }
  const template=await readFile(path.join(root,'vendor/harbor.yml.tmpl'));
  assert.equal(createHash('sha256').update(template).digest('hex'),lock.template_sha256);
  for (const recovery of [false,true]) {
    const compose=buildCompose(lock,recovery);
    const filename=recovery?'compose.restore.yaml':'compose.yaml';
    const expected='# Generated by tools/render-compose.mjs from images.lock.json. Edit the generator, then regenerate.\n'+yaml(compose);
    assert.equal(await readFile(path.join(root,filename),'utf8'),expected,filename+' must be regenerated');
    for (const [name,service] of Object.entries(compose.services)) {
      assert.ok(!service.container_name);
      assert.ok(!service.ports,name+' must not publish ports');
      assert.ok(!service.privileged);
      assert.ok(!service.env_file,'Runtime generated env_file cannot be used by Compose');
      assert.ok(!JSON.stringify(service.volumes).includes('docker.sock'));
      assert.equal(service.logging.driver,'local');
      if (name!=='proxy') assert.ok(!service.networks.includes('dokploy-network'));
    }
    assert.equal(compose.services.operations.build.target,'runtime');
    assert.equal(compose.services.operations.volumes.filter(v=>v.target==='/backup/manifest')[0].source,'manifest');
    if (recovery) assert.deepEqual(Object.keys(compose.services),['harbor-init','operations']);
    else {
      assert.equal(compose.services.proxy.entrypoint[1],'/etc/nginx/launch.sh');
      assert.ok(compose.services.postgresql.healthcheck.test.includes('/run/harbor-config/health.sh'));
      for(const name of ['core','postgresql','registry','registryctl','redis','jobservice','portal','proxy','trivy-adapter','exporter']) {
        assert.equal(compose.services[name].depends_on['harbor-init'].condition,'service_completed_successfully');
      }
    }
  }
  return 'Version lock, template integrity, generated Compose, network, persistence and security checks passed';
}
if (typeof process!=='undefined' && process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href===import.meta.url) console.log(await check());
